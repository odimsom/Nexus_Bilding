using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NexusBilling.Core.Domain.Common;
using NexusBilling.Core.Domain.Administration.Entities;

namespace NexusBilling.Infrastructure.Persistence.Administration.Configurations;

public class ContractGroupConfiguration : IEntityTypeConfiguration<ContractGroup>
{
    public void Configure(EntityTypeBuilder<ContractGroup> builder)
    {
        builder.ToTable("contract_group", "administration");
        builder.HasKey(x => x.Id);
        builder.Property(x => x.TenantId).HasConversion(v => v.Value, v => TenantIdentifier.Create(v)).HasColumnName("tenant_id").IsRequired();
        builder.Property(x => x.Code).HasColumnName("code");
        builder.Property(x => x.Description).HasColumnName("description");
        builder.Property(x => x.DiscOnContrOrdersOnly).HasColumnName("disc_on_contr_orders_only");
    }
}
